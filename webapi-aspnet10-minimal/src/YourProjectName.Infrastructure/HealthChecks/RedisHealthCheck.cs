using Microsoft.Extensions.Diagnostics.HealthChecks;
using StackExchange.Redis;

namespace YourProjectName.Infrastructure.HealthChecks;

internal sealed class RedisHealthCheck(IConnectionMultiplexer connectionMultiplexer) : IHealthCheck
{
    public async Task<HealthCheckResult> CheckHealthAsync(
        HealthCheckContext context,
        CancellationToken cancellationToken = default)
    {
        try
        {
            _ = await connectionMultiplexer.GetDatabase().PingAsync();

            return HealthCheckResult.Healthy();
        }
        catch (Exception ex)
        {
            return HealthCheckResult.Unhealthy(exception: ex);
        }
    }
}
